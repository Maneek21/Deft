import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sharedSourceRoot = resolve(packageRoot, '..', 'shared', 'src');
const outputRoot = resolve(packageRoot, 'dist', 'module-contract');

async function transpileAuthoritativeSource(name) {
  const sourcePath = resolve(sharedSourceRoot, `${name}.ts`);
  const outputPath = resolve(outputRoot, `${name}.js`);
  let source = await readFile(sourcePath, 'utf8');

  if (name === 'modules') {
    const portableImport = "from './schemas.js'";
    const originalImport = "from './schemas'";
    if (!source.includes(originalImport)) {
      throw new Error(`Expected authoritative Module schema import in ${sourcePath}`);
    }
    source = source.replace(originalImport, portableImport);
  }

  const result = ts.transpileModule(source, {
    fileName: sourcePath,
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022,
      verbatimModuleSyntax: true,
    },
    reportDiagnostics: true,
  });
  const errors = (result.diagnostics ?? []).filter(
    (diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error,
  );
  if (errors.length > 0) {
    throw new Error(ts.formatDiagnostics(errors, {
      getCanonicalFileName: (value) => value,
      getCurrentDirectory: () => packageRoot,
      getNewLine: () => '\n',
    }));
  }

  await mkdir(outputRoot, { recursive: true });
  await writeFile(
    outputPath,
    `// Generated from packages/shared/src/${name}.ts. Do not edit this file.\n${result.outputText}`,
    'utf8',
  );
}

await transpileAuthoritativeSource('schemas');
await transpileAuthoritativeSource('modules');
